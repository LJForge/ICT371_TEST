-- (g) Batch procedure: process only PENDING applications via query FOR loop.
CREATE OR REPLACE PROCEDURE ict371_q10.pr_assess_pending()
LANGUAGE plpgsql
SET search_path = ict371_q10, pg_temp
AS $$
DECLARE v_application RECORD;
BEGIN
    FOR v_application IN
        SELECT application_id
        FROM ict371_q10.applications
        WHERE status = 'PENDING'
        ORDER BY application_id
    LOOP
        CALL ict371_q10.pr_assess_application(v_application.application_id);
    END LOOP;
END;
$$;

