-- (b) FUNCTION: all three qualification rules and invalid-input checks.
CREATE OR REPLACE FUNCTION ict371_q10.fn_scholarship_eligible(
    p_age INTEGER, p_income NUMERIC, p_mark NUMERIC
)
RETURNS BOOLEAN
LANGUAGE plpgsql
IMMUTABLE
AS $$
BEGIN
    IF p_age IS NULL OR p_income IS NULL OR p_mark IS NULL THEN
        RAISE EXCEPTION 'Age, income and average mark cannot be NULL';
    END IF;
    IF p_age <= 0 THEN RAISE EXCEPTION 'Age must be positive'; END IF;
    IF p_income < 0 THEN RAISE EXCEPTION 'Monthly income cannot be negative'; END IF;
    IF p_mark < 0 OR p_mark > 100 THEN
        RAISE EXCEPTION 'Average mark must be between 0 and 100';
    END IF;

    RETURN p_age BETWEEN 18 AND 25
       AND p_income <= 3000
       AND p_mark >= 70;
END;
$$;

-- (d) TRIGGER: audit actual status changes only.
CREATE OR REPLACE FUNCTION ict371_q10.trg_fn_decision_audit()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ict371_q10, pg_temp
AS $$
BEGIN
    IF OLD.status IS DISTINCT FROM NEW.status THEN
        INSERT INTO ict371_q10.decision_audit
            (application_id, old_status, new_status, changed_at)
        VALUES
            (NEW.application_id, OLD.status, NEW.status, CURRENT_TIMESTAMP);
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_application_decision_audit
AFTER UPDATE OF status ON ict371_q10.applications
FOR EACH ROW
EXECUTE FUNCTION ict371_q10.trg_fn_decision_audit();

-- (c) PROCEDURE: only an existing PENDING application may be assessed.
CREATE OR REPLACE PROCEDURE ict371_q10.pr_assess_application(p_application_id INTEGER)
LANGUAGE plpgsql
SET search_path = ict371_q10, pg_temp
AS $$
DECLARE v_age INTEGER; v_income NUMERIC(12,2); v_mark NUMERIC(5,2);
        v_status VARCHAR(10); v_new_status VARCHAR(10);
BEGIN
    IF p_application_id IS NULL THEN
        RAISE EXCEPTION 'Application ID cannot be NULL';
    END IF;

    SELECT age_at_application, monthly_income, average_mark, status
      INTO v_age, v_income, v_mark, v_status
      FROM ict371_q10.applications
     WHERE application_id = p_application_id
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Application % does not exist', p_application_id;
    END IF;
    IF v_status <> 'PENDING' THEN
        RAISE EXCEPTION 'Application % has already been assessed (status: %)',
            p_application_id, v_status;
    END IF;

    IF ict371_q10.fn_scholarship_eligible(v_age, v_income, v_mark) THEN
        v_new_status := 'APPROVED';
    ELSE
        v_new_status := 'REJECTED';
    END IF;

    UPDATE ict371_q10.applications
       SET status = v_new_status
     WHERE application_id = p_application_id;
END;
$$;

-- (e) VIEW: approved applicants only; household income is deliberately omitted.
CREATE OR REPLACE VIEW ict371_q10.v_approved_applicants AS
SELECT s.student_number, s.full_name, a.average_mark, a.status
FROM ict371_q10.applications a
JOIN ict371_q10.students s ON s.student_id = a.student_id
WHERE a.status = 'APPROVED';

