-- ============================================================================

CREATE OR REPLACE FUNCTION ict371_q2.trg_fn_payment_audit()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ict371_q2, pg_temp
AS $$
BEGIN
    INSERT INTO ict371_q2.payment_audit
        (payment_id, student_id, amount, logged_at)
    VALUES
        (NEW.payment_id, NEW.student_id, NEW.amount, CURRENT_TIMESTAMP);

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_payment_audit_after_insert
AFTER INSERT ON ict371_q2.payments
FOR EACH ROW
EXECUTE FUNCTION ict371_q2.trg_fn_payment_audit();



