CREATE OR REPLACE PROCEDURE ict371_q2.pr_refresh_collections(
    p_day DATE
)
LANGUAGE plpgsql
SET search_path = ict371_q2, pg_temp
AS $$
DECLARE
    v_payment_count INTEGER;
    v_total_amount  NUMERIC(14,2);
BEGIN
    IF p_day IS NULL THEN
        RAISE EXCEPTION 'Collection date cannot be NULL';
    END IF;

    SELECT
        COUNT(*)::INTEGER,
        COALESCE(SUM(amount), 0)::NUMERIC(14,2)
    INTO
        v_payment_count,
        v_total_amount
    FROM ict371_q2.payments
    WHERE paid_on = p_day;

    INSERT INTO ict371_q2.daily_collections
        (collection_date, payment_count, total_amount)
    VALUES
        (p_day, v_payment_count, v_total_amount)
    ON CONFLICT (collection_date)
    DO UPDATE SET
        payment_count = EXCLUDED.payment_count,
        total_amount  = EXCLUDED.total_amount;
END;
$$;

