CREATE TABLE ict371_q2.students (
    student_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_number  VARCHAR(20) NOT NULL UNIQUE,
    full_name       VARCHAR(100) NOT NULL,
    fee_due         NUMERIC(12,2) NOT NULL CHECK (fee_due >= 0)
);

CREATE TABLE ict371_q2.payments (
    payment_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id  INTEGER NOT NULL
                REFERENCES ict371_q2.students(student_id),
    amount      NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    paid_on     DATE NOT NULL
);

CREATE TABLE ict371_q2.payment_audit (
    audit_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id  INTEGER NOT NULL
                REFERENCES ict371_q2.payments(payment_id),
    student_id  INTEGER NOT NULL
                REFERENCES ict371_q2.students(student_id),
    amount      NUMERIC(12,2) NOT NULL,
    logged_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ict371_q2.daily_collections (
    collection_date DATE PRIMARY KEY,
    payment_count   INTEGER NOT NULL CHECK (payment_count >= 0),
    total_amount    NUMERIC(14,2) NOT NULL CHECK (total_amount >= 0)
);

