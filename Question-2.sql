-- ============================================================================
-- (b) FUNCTION
-- ============================================================================

CREATE OR REPLACE FUNCTION ict371_q2.fn_fee_balance(
    p_student_id INTEGER
)
RETURNS NUMERIC(12,2)
LANGUAGE plpgsql
STABLE
SET search_path = ict371_q2, pg_temp
AS $$
DECLARE
    v_fee_due       NUMERIC(12,2);
    v_total_paid    NUMERIC(14,2);
BEGIN
    IF p_student_id IS NULL THEN
        RAISE EXCEPTION 'Student ID cannot be NULL';
    END IF;

    SELECT s.fee_due
      INTO v_fee_due
      FROM ict371_q2.students AS s
     WHERE s.student_id = p_student_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Student % does not exist', p_student_id;
    END IF;

    SELECT COALESCE(SUM(p.amount), 0)
      INTO v_total_paid
      FROM ict371_q2.payments AS p
     WHERE p.student_id = p_student_id;

    RETURN v_fee_due - v_total_paid;
END;
$$;

-- ============================================================================
-- (c) PROCEDURE
-- ============================================================================

CREATE OR REPLACE PROCEDURE ict371_q2.pr_receive_payment(
    p_student_id INTEGER,
    p_amount     NUMERIC(12,2),
    p_paid_on    DATE
)
LANGUAGE plpgsql
SET search_path = ict371_q2, pg_temp
AS $$
DECLARE
    v_balance NUMERIC(12,2);
BEGIN
    IF p_student_id IS NULL THEN
        RAISE EXCEPTION 'Student ID cannot be NULL';
    END IF;

    IF p_amount IS NULL OR p_amount <= 0 THEN
        RAISE EXCEPTION 'Payment amount must be greater than zero';
    END IF;

    IF p_paid_on IS NULL THEN
        RAISE EXCEPTION 'Payment date cannot be NULL';
    END IF;

    -- Lock the student row to prevent concurrent payments overspending balance.
    PERFORM 1
      FROM ict371_q2.students
     WHERE student_id = p_student_id
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Student % does not exist', p_student_id;
    END IF;

    v_balance := ict371_q2.fn_fee_balance(p_student_id);

    IF p_amount > v_balance THEN
        RAISE EXCEPTION
            'Payment of % exceeds student % outstanding balance of %',
            p_amount, p_student_id, v_balance;
    END IF;

    INSERT INTO ict371_q2.payments (student_id, amount, paid_on)
    VALUES (p_student_id, p_amount, p_paid_on);

    -- The AFTER INSERT trigger writes the audit record automatically.
END;
$$;

