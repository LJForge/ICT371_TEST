-- (c) PROCEDURE: return a loan and save its final fine in the same transaction.
CREATE OR REPLACE PROCEDURE ict371_q3.pr_return_loan(
    p_loan_id INTEGER,
    p_returned_on DATE
)
LANGUAGE plpgsql
SET search_path = ict371_q3, pg_temp
AS $$
DECLARE
    v_borrowed DATE;
    v_due DATE;
    v_existing_return DATE;
    v_final_fine NUMERIC(12,2);
BEGIN
    IF p_loan_id IS NULL OR p_returned_on IS NULL THEN
        RAISE EXCEPTION 'Loan ID and return date cannot be NULL';
    END IF;

    SELECT borrowed_on, due_on, returned_on
      INTO v_borrowed, v_due, v_existing_return
      FROM ict371_q3.loans
     WHERE loan_id = p_loan_id
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Loan % does not exist', p_loan_id;
    END IF;
    IF v_existing_return IS NOT NULL THEN
        RAISE EXCEPTION 'Loan % has already been returned', p_loan_id;
    END IF;
    IF p_returned_on < v_borrowed THEN
        RAISE EXCEPTION 'Return date cannot be before borrowed date';
    END IF;

    v_final_fine := GREATEST(0, p_returned_on - v_due) * 2.00;

    UPDATE ict371_q3.loans
       SET returned_on = p_returned_on,
           fine_amount = v_final_fine
     WHERE loan_id = p_loan_id;
END;
$$;

-- (e) VIEW: currently open loans overdue as of today.
CREATE OR REPLACE VIEW ict371_q3.v_overdue_loans AS
SELECT
    b.title,
    l.borrower_name,
    l.due_on,
    ict371_q3.fn_loan_fine(l.loan_id, CURRENT_DATE) AS fine_as_of_today
FROM ict371_q3.loans AS l
JOIN ict371_q3.books AS b ON b.book_id = l.book_id
WHERE l.returned_on IS NULL
  AND l.due_on < CURRENT_DATE;

-- (f) INDEX: book_id equality plus returned_on condition.
CREATE INDEX idx_loans_book_open
