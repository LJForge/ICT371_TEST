-- (b) FUNCTION: K2 per day after due date. A return stops further fine accrual.
CREATE OR REPLACE FUNCTION ict371_q3.fn_loan_fine(
    p_loan_id INTEGER,
    p_as_of DATE
)
RETURNS NUMERIC(12,2)
LANGUAGE plpgsql
STABLE
SET search_path = ict371_q3, pg_temp
AS $$
DECLARE
    v_due DATE;
    v_returned DATE;
    v_effective_date DATE;
BEGIN
    IF p_loan_id IS NULL OR p_as_of IS NULL THEN
        RAISE EXCEPTION 'Loan ID and calculation date cannot be NULL';
    END IF;

    SELECT due_on, returned_on
      INTO v_due, v_returned
      FROM ict371_q3.loans
     WHERE loan_id = p_loan_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Loan % does not exist', p_loan_id;
    END IF;

    v_effective_date := LEAST(p_as_of, COALESCE(v_returned, p_as_of));

    RETURN GREATEST(0, v_effective_date - v_due) * 2.00;
END;
$$;

-- (d) TRIGGER FUNCTION AND TRIGGER: audit only actual return-date changes.
CREATE OR REPLACE FUNCTION ict371_q3.trg_fn_loan_audit()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ict371_q3, pg_temp
AS $$
BEGIN
    IF OLD.returned_on IS DISTINCT FROM NEW.returned_on THEN
        INSERT INTO ict371_q3.loan_audit
            (loan_id, old_returned_on, new_returned_on, changed_at)
        VALUES
            (NEW.loan_id, OLD.returned_on, NEW.returned_on, CURRENT_TIMESTAMP);
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_loan_return_audit
AFTER UPDATE OF returned_on ON ict371_q3.loans
FOR EACH ROW
EXECUTE FUNCTION ict371_q3.trg_fn_loan_audit();

