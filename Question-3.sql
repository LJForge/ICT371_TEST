-- (g) SUMMARY PROCEDURE: loans not yet returned as of p_as_of.
CREATE OR REPLACE PROCEDURE ict371_q3.pr_refresh_overdue(p_as_of DATE)
LANGUAGE plpgsql
SET search_path = ict371_q3, pg_temp
AS $$
DECLARE
    v_count INTEGER;
    v_fine NUMERIC(14,2);
BEGIN
    IF p_as_of IS NULL THEN
        RAISE EXCEPTION 'Snapshot date cannot be NULL';
    END IF;

    SELECT COUNT(*)::INTEGER,
           COALESCE(SUM(ict371_q3.fn_loan_fine(loan_id, p_as_of)), 0)
      INTO v_count, v_fine
      FROM ict371_q3.loans
     WHERE borrowed_on <= p_as_of
       AND (returned_on IS NULL OR returned_on > p_as_of);

    INSERT INTO ict371_q3.overdue_summary(snapshot_date, overdue_count, total_fine)
    VALUES (p_as_of, v_count, v_fine)
    ON CONFLICT (snapshot_date)
    DO UPDATE SET overdue_count = EXCLUDED.overdue_count,
                  total_fine = EXCLUDED.total_fine;
END;
$$;

