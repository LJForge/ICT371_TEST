-- (b) FUNCTION: count a doctor's non-cancelled appointments on a date.
CREATE OR REPLACE FUNCTION ict371_q4.fn_daily_load(
    p_doctor_id INTEGER, p_day DATE
)
RETURNS INTEGER
LANGUAGE plpgsql
STABLE
SET search_path = ict371_q4, pg_temp
AS $$
DECLARE v_count INTEGER;
BEGIN
    IF p_doctor_id IS NULL OR p_day IS NULL THEN
        RAISE EXCEPTION 'Doctor ID and day cannot be NULL';
    END IF;

    PERFORM 1 FROM ict371_q4.doctors WHERE doctor_id = p_doctor_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Doctor % does not exist', p_doctor_id;
    END IF;

    SELECT COUNT(*)::INTEGER INTO v_count
    FROM ict371_q4.appointments
    WHERE doctor_id = p_doctor_id
      AND appointment_day = p_day
      AND status <> 'CANCELLED';

    RETURN COALESCE(v_count, 0);
END;
$$;

-- (c) PROCEDURE: validate patient, doctor, date and slot before booking.
CREATE OR REPLACE PROCEDURE ict371_q4.pr_book_appointment(
    p_patient_id INTEGER,
    p_doctor_id INTEGER,
    p_day DATE,
    p_slot TIME
)
LANGUAGE plpgsql
SET search_path = ict371_q4, pg_temp
AS $$
BEGIN
    IF p_patient_id IS NULL OR p_doctor_id IS NULL
       OR p_day IS NULL OR p_slot IS NULL THEN
        RAISE EXCEPTION 'Patient, doctor, date and slot are required';
    END IF;
    IF p_day < CURRENT_DATE THEN
        RAISE EXCEPTION 'Cannot book an appointment in the past';
    END IF;
    IF p_slot NOT IN (TIME '09:00', TIME '10:00', TIME '11:00', TIME '12:00') THEN
        RAISE EXCEPTION 'Unsupported appointment slot: %', p_slot;
    END IF;
    PERFORM 1 FROM ict371_q4.patients WHERE patient_id = p_patient_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Patient % does not exist', p_patient_id; END IF;
    PERFORM 1 FROM ict371_q4.doctors WHERE doctor_id = p_doctor_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Doctor % does not exist', p_doctor_id; END IF;

    INSERT INTO ict371_q4.appointments
        (patient_id, doctor_id, appointment_day, slot_time, status)
    VALUES (p_patient_id, p_doctor_id, p_day, p_slot, 'BOOKED');
END;
$$;

-- (e) VIEW: only today's BOOKED appointments; exposes only requested names/slot.
CREATE OR REPLACE VIEW ict371_q4.v_today_appointments AS
SELECT p.full_name AS patient_name,
       d.full_name AS doctor_name,
       a.slot_time
FROM ict371_q4.appointments a
JOIN ict371_q4.patients p ON p.patient_id = a.patient_id
JOIN ict371_q4.doctors d ON d.doctor_id = a.doctor_id
WHERE a.appointment_day = CURRENT_DATE
  AND a.status = 'BOOKED';

