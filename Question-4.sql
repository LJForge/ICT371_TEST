-- (d) TRIGGER: lock the doctor row to serialize bookings for that doctor.
-- This protects the slot rule for direct INSERT/UPDATE statements as well.
CREATE OR REPLACE FUNCTION ict371_q4.trg_fn_check_appointment_clash()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ict371_q4, pg_temp
AS $$
BEGIN
    IF NEW.status <> 'CANCELLED' THEN
        PERFORM 1
          FROM ict371_q4.doctors
         WHERE doctor_id = NEW.doctor_id
         FOR UPDATE;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Doctor % does not exist', NEW.doctor_id;
        END IF;

        IF EXISTS (
            SELECT 1
              FROM ict371_q4.appointments a
             WHERE a.doctor_id = NEW.doctor_id
               AND a.appointment_day = NEW.appointment_day
               AND a.slot_time = NEW.slot_time
               AND a.status <> 'CANCELLED'
               AND (TG_OP = 'INSERT' OR a.appointment_id <> NEW.appointment_id)
        ) THEN
            RAISE EXCEPTION
                'Doctor % already has a non-cancelled appointment on % at %',
                NEW.doctor_id, NEW.appointment_day, NEW.slot_time;
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_appointment_no_clash
BEFORE INSERT OR UPDATE ON ict371_q4.appointments
FOR EACH ROW
EXECUTE FUNCTION ict371_q4.trg_fn_check_appointment_clash();

