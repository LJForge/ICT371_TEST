DROP TABLE IF EXISTS ict371_q4.patients CASCADE;

CREATE TABLE ict371_q4.patients (
    patient_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL
);

CREATE TABLE ict371_q4.doctors (
    doctor_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL
);

CREATE TABLE ict371_q4.appointments (
    appointment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INTEGER NOT NULL REFERENCES ict371_q4.patients(patient_id),
    doctor_id INTEGER NOT NULL REFERENCES ict371_q4.doctors(doctor_id),
    appointment_day DATE NOT NULL,
    slot_time TIME NOT NULL CHECK (slot_time IN
        (TIME '09:00', TIME '10:00', TIME '11:00', TIME '12:00')),
    status VARCHAR(10) NOT NULL DEFAULT 'BOOKED'
        CHECK (status IN ('BOOKED', 'ATTENDED', 'CANCELLED'))
);

CREATE TABLE ict371_q4.clinic_summary (
    summary_date DATE PRIMARY KEY,
    booked_count INTEGER NOT NULL CHECK (booked_count >= 0),
    attended_count INTEGER NOT NULL CHECK (attended_count >= 0),
    cancelled_count INTEGER NOT NULL CHECK (cancelled_count >= 0)
);

