-- (g) SUMMARY PROCEDURE: count each status for the specified day.
CREATE OR REPLACE PROCEDURE ict371_q4.pr_refresh_clinic_summary(p_day DATE)
LANGUAGE plpgsql
SET search_path = ict371_q4, pg_temp
AS $$
DECLARE v_booked INTEGER; v_attended INTEGER; v_cancelled INTEGER;
BEGIN
    IF p_day IS NULL THEN RAISE EXCEPTION 'Summary date cannot be NULL'; END IF;

    SELECT COUNT(*) FILTER (WHERE status = 'BOOKED')::INTEGER,
           COUNT(*) FILTER (WHERE status = 'ATTENDED')::INTEGER,
           COUNT(*) FILTER (WHERE status = 'CANCELLED')::INTEGER
      INTO v_booked, v_attended, v_cancelled
      FROM ict371_q4.appointments
     WHERE appointment_day = p_day;

    INSERT INTO ict371_q4.clinic_summary
        (summary_date, booked_count, attended_count, cancelled_count)
    VALUES (p_day, v_booked, v_attended, v_cancelled)
    ON CONFLICT (summary_date)
    DO UPDATE SET booked_count = EXCLUDED.booked_count,
                  attended_count = EXCLUDED.attended_count,
                  cancelled_count = EXCLUDED.cancelled_count;
END;
$$;

