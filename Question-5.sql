-- (g) SNAPSHOT PROCEDURE: one row per date and room; rerun replaces values.
CREATE OR REPLACE PROCEDURE ict371_q5.pr_refresh_occupancy()
LANGUAGE plpgsql
SET search_path = ict371_q5, pg_temp
AS $$
BEGIN
    INSERT INTO ict371_q5.occupancy_snapshot
        (snapshot_date, room_id, occupied_beds, free_beds)
    SELECT CURRENT_DATE, r.room_id,
           COUNT(a.allocation_id)::INTEGER,
           r.capacity - COUNT(a.allocation_id)::INTEGER
    FROM ict371_q5.rooms r
    LEFT JOIN ict371_q5.allocations a
      ON a.room_id = r.room_id AND a.status = 'ACTIVE'
    GROUP BY r.room_id, r.capacity
    ON CONFLICT (snapshot_date, room_id)
    DO UPDATE SET occupied_beds = EXCLUDED.occupied_beds,
                  free_beds = EXCLUDED.free_beds;
END;
$$;

