-- (d) TRIGGER: lock room and student rows to protect capacity and one-active rule.
CREATE OR REPLACE FUNCTION ict371_q5.trg_fn_validate_allocation()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ict371_q5, pg_temp
AS $$
DECLARE v_capacity INTEGER; v_occupied INTEGER;
BEGIN
    PERFORM 1 FROM ict371_q5.students
     WHERE student_id = NEW.student_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Student % does not exist', NEW.student_id; END IF;

    SELECT capacity INTO v_capacity
      FROM ict371_q5.rooms
     WHERE room_id = NEW.room_id
     FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Room % does not exist', NEW.room_id; END IF;

    IF NEW.status = 'ACTIVE' THEN
        IF EXISTS (
            SELECT 1 FROM ict371_q5.allocations a
             WHERE a.student_id = NEW.student_id
               AND a.status = 'ACTIVE'
               AND (TG_OP = 'INSERT' OR a.allocation_id <> NEW.allocation_id)
        ) THEN
            RAISE EXCEPTION 'Student % already has an ACTIVE allocation', NEW.student_id;
        END IF;

        SELECT COUNT(*)::INTEGER INTO v_occupied
          FROM ict371_q5.allocations a
         WHERE a.room_id = NEW.room_id
           AND a.status = 'ACTIVE'
           AND (TG_OP = 'INSERT' OR a.allocation_id <> NEW.allocation_id);

        IF v_occupied >= v_capacity THEN
            RAISE EXCEPTION 'Room % is full (capacity %)', NEW.room_id, v_capacity;
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_allocation_capacity
BEFORE INSERT OR UPDATE ON ict371_q5.allocations
FOR EACH ROW
EXECUTE FUNCTION ict371_q5.trg_fn_validate_allocation();

