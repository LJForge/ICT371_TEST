-- (b) FUNCTION: room capacity minus its ACTIVE allocations.
CREATE OR REPLACE FUNCTION ict371_q5.fn_free_beds(p_room_id INTEGER)
RETURNS INTEGER
LANGUAGE plpgsql
STABLE
SET search_path = ict371_q5, pg_temp
AS $$
DECLARE v_capacity INTEGER; v_occupied INTEGER;
BEGIN
    IF p_room_id IS NULL THEN RAISE EXCEPTION 'Room ID cannot be NULL'; END IF;
    SELECT capacity INTO v_capacity FROM ict371_q5.rooms WHERE room_id = p_room_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Room % does not exist', p_room_id; END IF;

    SELECT COUNT(*)::INTEGER INTO v_occupied
    FROM ict371_q5.allocations
    WHERE room_id = p_room_id AND status = 'ACTIVE';

    RETURN v_capacity - v_occupied;
END;
$$;

-- (c) PROCEDURE: validate IDs, active allocation and available bed.
CREATE OR REPLACE PROCEDURE ict371_q5.pr_allocate_room(
    p_student_id INTEGER, p_room_id INTEGER, p_allocated_on DATE
)
LANGUAGE plpgsql
SET search_path = ict371_q5, pg_temp
AS $$
BEGIN
    IF p_student_id IS NULL OR p_room_id IS NULL OR p_allocated_on IS NULL THEN
        RAISE EXCEPTION 'Student, room and allocation date are required';
    END IF;
    PERFORM 1 FROM ict371_q5.students WHERE student_id = p_student_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Student % does not exist', p_student_id; END IF;
    PERFORM 1 FROM ict371_q5.rooms WHERE room_id = p_room_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Room % does not exist', p_room_id; END IF;

    -- The trigger repeats critical checks for direct SQL inserts and updates.
    INSERT INTO ict371_q5.allocations
        (student_id, room_id, allocated_on, released_on, status)
    VALUES (p_student_id, p_room_id, p_allocated_on, NULL, 'ACTIVE');
END;
$$;

-- (e) VIEW: every room, including empty rooms.
CREATE OR REPLACE VIEW ict371_q5.v_room_occupancy AS
SELECT r.room_id, r.room_number, r.capacity,
       COUNT(a.allocation_id)::INTEGER AS occupied_beds,
       r.capacity - COUNT(a.allocation_id)::INTEGER AS free_beds
FROM ict371_q5.rooms r
LEFT JOIN ict371_q5.allocations a
  ON a.room_id = r.room_id AND a.status = 'ACTIVE'
GROUP BY r.room_id, r.room_number, r.capacity;

