-- (a) DATABASE AND SEED DATA
CREATE SCHEMA IF NOT EXISTS ict371_q5;
SET search_path TO ict371_q5, public;

DROP VIEW IF EXISTS ict371_q5.v_room_occupancy CASCADE;
