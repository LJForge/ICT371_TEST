DROP TABLE IF EXISTS ict371_q5.allocations CASCADE;
DROP TABLE IF EXISTS ict371_q5.rooms CASCADE;
DROP TABLE IF EXISTS ict371_q5.students CASCADE;

CREATE TABLE ict371_q5.students (
    student_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_number VARCHAR(20) NOT NULL UNIQUE,
    full_name VARCHAR(100) NOT NULL
);

CREATE TABLE ict371_q5.rooms (
    room_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_number VARCHAR(20) NOT NULL UNIQUE,
    capacity INTEGER NOT NULL CHECK (capacity > 0)
);

CREATE TABLE ict371_q5.allocations (
    allocation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL REFERENCES ict371_q5.students(student_id),
    room_id INTEGER NOT NULL REFERENCES ict371_q5.rooms(room_id),
    allocated_on DATE NOT NULL,
    released_on DATE,
    status VARCHAR(10) NOT NULL CHECK (status IN ('ACTIVE', 'ENDED')),
    CONSTRAINT chk_allocation_release CHECK (
        (status = 'ACTIVE' AND released_on IS NULL)
        OR (status = 'ENDED' AND released_on IS NOT NULL)
    ),
    CONSTRAINT chk_release_after_allocation CHECK (
        released_on IS NULL OR released_on >= allocated_on
    )
);

CREATE TABLE ict371_q5.occupancy_snapshot (
    snapshot_date DATE NOT NULL,
    room_id INTEGER NOT NULL REFERENCES ict371_q5.rooms(room_id),
    occupied_beds INTEGER NOT NULL CHECK (occupied_beds >= 0),
    free_beds INTEGER NOT NULL CHECK (free_beds >= 0),
    PRIMARY KEY (snapshot_date, room_id)
);

