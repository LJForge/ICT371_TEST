-- (a) DATABASE AND SEED DATA
CREATE SCHEMA IF NOT EXISTS ict371_q6;
SET search_path TO ict371_q6, public;

DROP VIEW IF EXISTS ict371_q6.v_payroll_report CASCADE;
DROP TABLE IF EXISTS ict371_q6.salary_audit CASCADE;
DROP TABLE IF EXISTS ict371_q6.payroll CASCADE;
DROP TABLE IF EXISTS ict371_q6.employees CASCADE;

CREATE TABLE ict371_q6.employees (
    employee_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    basic_salary NUMERIC(12,2) NOT NULL CHECK (basic_salary >= 0),
    allowance NUMERIC(12,2) NOT NULL CHECK (allowance >= 0),
    deduction NUMERIC(12,2) NOT NULL CHECK (deduction >= 0),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE ict371_q6.payroll (
    payroll_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL REFERENCES ict371_q6.employees(employee_id),
    pay_month DATE NOT NULL CHECK (EXTRACT(DAY FROM pay_month) = 1),
    gross_pay NUMERIC(12,2) NOT NULL CHECK (gross_pay >= 0),
    net_pay NUMERIC(12,2) NOT NULL CHECK (net_pay >= 0),
    CONSTRAINT uq_payroll_employee_month UNIQUE (employee_id, pay_month)
);

CREATE TABLE ict371_q6.salary_audit (
    audit_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL REFERENCES ict371_q6.employees(employee_id),
    old_salary NUMERIC(12,2) NOT NULL,
    new_salary NUMERIC(12,2) NOT NULL,
    changed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

