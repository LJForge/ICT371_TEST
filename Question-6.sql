-- (e) VIEW: include historical payroll even if employee is now inactive.
CREATE OR REPLACE VIEW ict371_q6.v_payroll_report AS
SELECT e.full_name, p.pay_month, p.gross_pay, p.net_pay
FROM ict371_q6.payroll p
JOIN ict371_q6.employees e ON e.employee_id = p.employee_id;

