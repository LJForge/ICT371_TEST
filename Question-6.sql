-- (b) FUNCTION: current basic salary + allowance - fixed deduction.
CREATE OR REPLACE FUNCTION ict371_q6.fn_net_pay(p_employee_id INTEGER)
RETURNS NUMERIC(12,2)
LANGUAGE plpgsql
STABLE
SET search_path = ict371_q6, pg_temp
AS $$
DECLARE v_basic NUMERIC(12,2); v_allowance NUMERIC(12,2);
        v_deduction NUMERIC(12,2); v_net NUMERIC(12,2);
BEGIN
    IF p_employee_id IS NULL THEN RAISE EXCEPTION 'Employee ID cannot be NULL'; END IF;

    SELECT basic_salary, allowance, deduction
      INTO v_basic, v_allowance, v_deduction
      FROM ict371_q6.employees
     WHERE employee_id = p_employee_id;

    IF NOT FOUND THEN RAISE EXCEPTION 'Employee % does not exist', p_employee_id; END IF;

    v_net := v_basic + v_allowance - v_deduction;
    IF v_net < 0 THEN
        RAISE EXCEPTION 'Employee % has a negative calculated net pay: %',
            p_employee_id, v_net;
    END IF;
    RETURN v_net;
END;
$$;

-- (d) TRIGGER: log only an actual basic_salary change.
CREATE OR REPLACE FUNCTION ict371_q6.trg_fn_salary_audit()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ict371_q6, pg_temp
AS $$
BEGIN
    IF OLD.basic_salary IS DISTINCT FROM NEW.basic_salary THEN
        INSERT INTO ict371_q6.salary_audit
            (employee_id, old_salary, new_salary, changed_at)
        VALUES
            (NEW.employee_id, OLD.basic_salary, NEW.basic_salary, CURRENT_TIMESTAMP);
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_employee_salary_audit
AFTER UPDATE OF basic_salary ON ict371_q6.employees
FOR EACH ROW
EXECUTE FUNCTION ict371_q6.trg_fn_salary_audit();

-- (c) PROCEDURE: process active employees using a query FOR loop.
-- Existing employee/month rows are left unchanged (ON CONFLICT DO NOTHING).
CREATE OR REPLACE PROCEDURE ict371_q6.pr_process_payroll(p_month DATE)
LANGUAGE plpgsql
SET search_path = ict371_q6, pg_temp
AS $$
DECLARE v_employee RECORD; v_net NUMERIC(12,2); v_gross NUMERIC(12,2);
BEGIN
    IF p_month IS NULL OR EXTRACT(DAY FROM p_month) <> 1 THEN
        RAISE EXCEPTION 'Pay month must be the first day of a month';
    END IF;

    FOR v_employee IN
        SELECT employee_id, basic_salary, allowance
        FROM ict371_q6.employees
        WHERE active = TRUE
        ORDER BY employee_id
    LOOP
        v_net := ict371_q6.fn_net_pay(v_employee.employee_id);
        v_gross := v_employee.basic_salary + v_employee.allowance;

        INSERT INTO ict371_q6.payroll
            (employee_id, pay_month, gross_pay, net_pay)
        VALUES
            (v_employee.employee_id, p_month, v_gross, v_net)
        ON CONFLICT (employee_id, pay_month) DO NOTHING;
    END LOOP;
END;
$$;

