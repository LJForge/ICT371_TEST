-- (d) TRIGGER: reject a meter reading lower than the previous reading.
CREATE OR REPLACE FUNCTION ict371_q7.trg_fn_validate_reading()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ict371_q7, pg_temp
AS $$
BEGIN
    IF NEW.previous_reading IS NULL OR NEW.current_reading IS NULL
       OR NEW.previous_reading < 0 OR NEW.current_reading < 0 THEN
        RAISE EXCEPTION 'Meter readings must be non-negative and not NULL';
    END IF;
    IF NEW.current_reading < NEW.previous_reading THEN
        RAISE EXCEPTION 'Current meter reading cannot be below previous reading';
    END IF;
    IF NEW.reading_month IS NULL OR EXTRACT(DAY FROM NEW.reading_month) <> 1 THEN
        RAISE EXCEPTION 'Reading month must be the first day of a month';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validate_meter_reading
BEFORE INSERT OR UPDATE ON ict371_q7.readings
FOR EACH ROW
EXECUTE FUNCTION ict371_q7.trg_fn_validate_reading();

