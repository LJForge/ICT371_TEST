-- (b) FUNCTION: first 10 units at K5, additional units at K8.
CREATE OR REPLACE FUNCTION ict371_q7.fn_water_charge(p_units NUMERIC)
RETURNS NUMERIC(12,2)
LANGUAGE plpgsql
IMMUTABLE
AS $$
BEGIN
    IF p_units IS NULL OR p_units < 0 THEN
        RAISE EXCEPTION 'Consumption must be a non-negative number';
    END IF;
    RETURN (LEAST(p_units, 10) * 5
          + GREATEST(p_units - 10, 0) * 8)::NUMERIC(12,2);
END;
$$;

-- (c) PROCEDURE: derive units from readings and create one bill.
CREATE OR REPLACE PROCEDURE ict371_q7.pr_generate_bill(
    p_reading_id INTEGER, p_due_on DATE
)
LANGUAGE plpgsql
SET search_path = ict371_q7, pg_temp
AS $$
DECLARE v_previous NUMERIC(12,2); v_current NUMERIC(12,2);
        v_units NUMERIC(12,2); v_charge NUMERIC(12,2);
BEGIN
    IF p_reading_id IS NULL OR p_due_on IS NULL THEN
        RAISE EXCEPTION 'Reading ID and due date are required';
    END IF;

    SELECT previous_reading, current_reading
      INTO v_previous, v_current
      FROM ict371_q7.readings
     WHERE reading_id = p_reading_id
     FOR UPDATE;

    IF NOT FOUND THEN RAISE EXCEPTION 'Reading % does not exist', p_reading_id; END IF;

    IF EXISTS (SELECT 1 FROM ict371_q7.bills WHERE reading_id = p_reading_id) THEN
        RAISE EXCEPTION 'A bill already exists for reading %', p_reading_id;
    END IF;

    v_units := v_current - v_previous;
    v_charge := ict371_q7.fn_water_charge(v_units);

    INSERT INTO ict371_q7.bills(reading_id, charge, amount_paid, due_on)
    VALUES (p_reading_id, v_charge, 0, p_due_on);
END;
$$;

