-- (e) VIEW: overdue bills with outstanding amount.
CREATE OR REPLACE VIEW ict371_q7.v_overdue_bills AS
SELECT c.full_name AS customer_name,
       b.due_on,
       (b.charge - b.amount_paid)::NUMERIC(12,2) AS outstanding_amount
FROM ict371_q7.bills b
JOIN ict371_q7.readings r ON r.reading_id = b.reading_id
JOIN ict371_q7.customers c ON c.customer_id = r.customer_id
WHERE b.due_on < CURRENT_DATE
  AND b.amount_paid < b.charge;

-- (f) INDEX: date-based search on overdue/unpaid bills.
CREATE INDEX idx_bills_unpaid_due
    ON ict371_q7.bills (due_on)
    WHERE amount_paid < charge;
ANALYZE ict371_q7.bills;

EXPLAIN
SELECT bill_id, reading_id, charge - amount_paid AS outstanding
FROM ict371_q7.bills
WHERE due_on < CURRENT_DATE
  AND amount_paid < charge;

-- (g) PROCEDURE: today's total outstanding bill balances, rerunnable safely.
CREATE OR REPLACE PROCEDURE ict371_q7.pr_refresh_receivables()
LANGUAGE plpgsql
SET search_path = ict371_q7, pg_temp
AS $$
DECLARE v_total NUMERIC(14,2);
BEGIN
    SELECT COALESCE(SUM(charge - amount_paid), 0)::NUMERIC(14,2)
      INTO v_total
      FROM ict371_q7.bills
     WHERE amount_paid < charge;

    INSERT INTO ict371_q7.receivable_snapshot(snapshot_date, total_due)
    VALUES (CURRENT_DATE, v_total)
    ON CONFLICT (snapshot_date)
    DO UPDATE SET total_due = EXCLUDED.total_due;
END;
$$;

CALL ict371_q7.pr_refresh_receivables();
