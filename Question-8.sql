-- (e) VIEW: vehicles currently at or above the 5,000 km threshold.
CREATE OR REPLACE VIEW ict371_q8.v_service_due AS
SELECT registration,
       (current_odometer - last_service_odometer)::NUMERIC(12,2) AS km_since_service
FROM ict371_q8.vehicles
WHERE current_odometer - last_service_odometer >= 5000;

-- (f) INDEX: vehicle equality followed by trip date range.
CREATE INDEX idx_trips_vehicle_trip_on
    ON ict371_q8.trips (vehicle_id, trip_on);
ANALYZE ict371_q8.trips;

EXPLAIN
SELECT trip_id, start_odometer, end_odometer
FROM ict371_q8.trips
WHERE vehicle_id = 1
  AND trip_on BETWEEN CURRENT_DATE - 30 AND CURRENT_DATE;

-- (g) Refresh alerts for due vehicles and remove alerts for vehicles no longer due.
CREATE OR REPLACE PROCEDURE ict371_q8.pr_refresh_service_alerts()
LANGUAGE plpgsql
SET search_path = ict371_q8, pg_temp
AS $$
BEGIN
    DELETE FROM ict371_q8.service_alerts a
    WHERE NOT EXISTS (
        SELECT 1
        FROM ict371_q8.vehicles v
        WHERE v.vehicle_id = a.vehicle_id
          AND v.current_odometer - v.last_service_odometer >= 5000
    );

    INSERT INTO ict371_q8.service_alerts(vehicle_id, km_since_service, flagged_on)
    SELECT vehicle_id,
           (current_odometer - last_service_odometer)::NUMERIC(12,2),
           CURRENT_DATE
    FROM ict371_q8.vehicles
    WHERE current_odometer - last_service_odometer >= 5000
    ON CONFLICT (vehicle_id)
    DO UPDATE SET km_since_service = EXCLUDED.km_since_service,
                  flagged_on = EXCLUDED.flagged_on;
END;
$$;

CALL ict371_q8.pr_refresh_service_alerts();
