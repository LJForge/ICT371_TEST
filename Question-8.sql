-- (d) TRIGGER: trip must start at current odometer; update it once.
-- Lock the vehicle row so simultaneous trips cannot use a stale odometer.
CREATE OR REPLACE FUNCTION ict371_q8.trg_fn_trip_odometer()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ict371_q8, pg_temp
AS $$
DECLARE v_current NUMERIC(12,2);
BEGIN
    IF NEW.start_odometer IS NULL OR NEW.end_odometer IS NULL
       OR NEW.start_odometer < 0 OR NEW.end_odometer <= NEW.start_odometer THEN
        RAISE EXCEPTION 'Trip end odometer must be greater than a non-negative start';
    END IF;

    SELECT current_odometer INTO v_current
      FROM ict371_q8.vehicles
     WHERE vehicle_id = NEW.vehicle_id
     FOR UPDATE;

    IF NOT FOUND THEN RAISE EXCEPTION 'Vehicle % does not exist', NEW.vehicle_id; END IF;

    IF NEW.start_odometer <> v_current THEN
        RAISE EXCEPTION 'Trip must start at current odometer %. Supplied start: %',
            v_current, NEW.start_odometer;
    END IF;

    UPDATE ict371_q8.vehicles
       SET current_odometer = NEW.end_odometer
     WHERE vehicle_id = NEW.vehicle_id;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_trip_update_odometer
BEFORE INSERT ON ict371_q8.trips
FOR EACH ROW
EXECUTE FUNCTION ict371_q8.trg_fn_trip_odometer();

-- (b) FUNCTION: true when 5,000 km or more have been travelled since service.
CREATE OR REPLACE FUNCTION ict371_q8.fn_service_due(p_vehicle_id INTEGER)
RETURNS BOOLEAN
LANGUAGE plpgsql
STABLE
SET search_path = ict371_q8, pg_temp
AS $$
DECLARE v_current NUMERIC(12,2); v_last NUMERIC(12,2);
BEGIN
    IF p_vehicle_id IS NULL THEN RAISE EXCEPTION 'Vehicle ID cannot be NULL'; END IF;
    SELECT current_odometer, last_service_odometer
      INTO v_current, v_last
      FROM ict371_q8.vehicles
     WHERE vehicle_id = p_vehicle_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Vehicle % does not exist', p_vehicle_id; END IF;
    RETURN (v_current - v_last) >= 5000;
END;
$$;

-- (c) PROCEDURE: insert trip only; trigger updates vehicle odometer.
CREATE OR REPLACE PROCEDURE ict371_q8.pr_record_trip(
    p_vehicle_id INTEGER, p_trip_on DATE,
    p_start NUMERIC(12,2), p_end NUMERIC(12,2)
)
LANGUAGE plpgsql
SET search_path = ict371_q8, pg_temp
AS $$
BEGIN
    IF p_vehicle_id IS NULL OR p_trip_on IS NULL OR p_start IS NULL OR p_end IS NULL THEN
        RAISE EXCEPTION 'Vehicle, trip date, start and end odometers are required';
    END IF;
    PERFORM 1 FROM ict371_q8.vehicles WHERE vehicle_id = p_vehicle_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Vehicle % does not exist', p_vehicle_id; END IF;
    IF p_end <= p_start THEN RAISE EXCEPTION 'End odometer must exceed start odometer'; END IF;

    INSERT INTO ict371_q8.trips(vehicle_id, trip_on, start_odometer, end_odometer)
    VALUES (p_vehicle_id, p_trip_on, p_start, p_end);
    -- Do not update vehicles here: the BEFORE INSERT trigger does that exactly once.
END;
$$;

