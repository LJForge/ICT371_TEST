-- (a) DATABASE AND SEED DATA
CREATE SCHEMA IF NOT EXISTS ict371_q8;
SET search_path TO ict371_q8, public;

DROP VIEW IF EXISTS ict371_q8.v_service_due CASCADE;
DROP TABLE IF EXISTS ict371_q8.service_alerts CASCADE;
DROP TABLE IF EXISTS ict371_q8.trips CASCADE;
DROP TABLE IF EXISTS ict371_q8.vehicles CASCADE;

CREATE TABLE ict371_q8.vehicles (
    vehicle_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration VARCHAR(20) NOT NULL UNIQUE,
    current_odometer NUMERIC(12,2) NOT NULL CHECK (current_odometer >= 0),
    last_service_odometer NUMERIC(12,2) NOT NULL CHECK (
        last_service_odometer >= 0
        AND last_service_odometer <= current_odometer
    )
);

CREATE TABLE ict371_q8.trips (
    trip_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id INTEGER NOT NULL REFERENCES ict371_q8.vehicles(vehicle_id),
    trip_on DATE NOT NULL,
    start_odometer NUMERIC(12,2) NOT NULL CHECK (start_odometer >= 0),
    end_odometer NUMERIC(12,2) NOT NULL CHECK (end_odometer >= 0),
    CHECK (end_odometer > start_odometer)
);

CREATE TABLE ict371_q8.service_alerts (
    vehicle_id INTEGER PRIMARY KEY REFERENCES ict371_q8.vehicles(vehicle_id),
    km_since_service NUMERIC(12,2) NOT NULL CHECK (km_since_service >= 5000),
    flagged_on DATE NOT NULL
);

