-- (b) FUNCTION: fixed hypothetical price for each grade.
CREATE OR REPLACE FUNCTION ict371_q9.fn_maize_rate(p_grade CHAR(1))
RETURNS NUMERIC(8,2)
LANGUAGE plpgsql
IMMUTABLE
AS $$
BEGIN
    IF p_grade IS NULL THEN RAISE EXCEPTION 'Maize grade cannot be NULL'; END IF;
    CASE UPPER(p_grade)
        WHEN 'A' THEN RETURN 5.00;
        WHEN 'B' THEN RETURN 4.00;
        WHEN 'C' THEN RETURN 3.00;
        ELSE RAISE EXCEPTION 'Unsupported maize grade: %', p_grade;
    END CASE;
END;
$$;

-- (d) TRIGGER: all inserts/updates, including direct SQL, use the same pricing.
CREATE OR REPLACE FUNCTION ict371_q9.trg_fn_price_delivery()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ict371_q9, pg_temp
AS $$
BEGIN
    IF NEW.weight_kg IS NULL OR NEW.weight_kg <= 0 THEN
        RAISE EXCEPTION 'Delivery weight must be greater than zero';
    END IF;
    IF NEW.grade IS NULL THEN RAISE EXCEPTION 'Grade cannot be NULL'; END IF;

    NEW.unit_rate := ict371_q9.fn_maize_rate(NEW.grade);
    NEW.total_value := ROUND(NEW.weight_kg * NEW.unit_rate, 2);
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_delivery_set_price
BEFORE INSERT OR UPDATE ON ict371_q9.deliveries
FOR EACH ROW
EXECUTE FUNCTION ict371_q9.trg_fn_price_delivery();

-- (c) PROCEDURE: supplies base fields; trigger calculates rate and value.
CREATE OR REPLACE PROCEDURE ict371_q9.pr_receive_delivery(
    p_farmer_id INTEGER, p_grade CHAR(1),
    p_weight NUMERIC(12,2), p_date DATE
)
LANGUAGE plpgsql
SET search_path = ict371_q9, pg_temp
AS $$
BEGIN
    IF p_farmer_id IS NULL OR p_grade IS NULL OR p_weight IS NULL OR p_date IS NULL THEN
        RAISE EXCEPTION 'Farmer, grade, weight and delivery date are required';
    END IF;
    PERFORM 1 FROM ict371_q9.farmers WHERE farmer_id = p_farmer_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Farmer % does not exist', p_farmer_id; END IF;
    IF p_weight <= 0 THEN RAISE EXCEPTION 'Delivery weight must be positive'; END IF;
    -- Validate grade early; trigger independently enforces the same rule.
    PERFORM ict371_q9.fn_maize_rate(p_grade);

    INSERT INTO ict371_q9.deliveries
        (farmer_id, grade, weight_kg, unit_rate, total_value, delivered_on, is_paid)
    VALUES
        (p_farmer_id, UPPER(p_grade), p_weight, 1, 1, p_date, FALSE);
END;
$$;

