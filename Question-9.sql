-- (e) VIEW: all farmers, including those with no unpaid deliveries; zero if none.
CREATE OR REPLACE VIEW ict371_q9.v_farmer_amount_due AS
SELECT f.farmer_number,
       f.full_name,
       COALESCE(SUM(d.total_value) FILTER (WHERE d.is_paid = FALSE), 0)::NUMERIC(14,2)
           AS total_unpaid_value
FROM ict371_q9.farmers f
LEFT JOIN ict371_q9.deliveries d ON d.farmer_id = f.farmer_id
GROUP BY f.farmer_id, f.farmer_number, f.full_name;

-- (f) INDEX: farmer equality followed by delivery date range.
CREATE INDEX idx_deliveries_farmer_date
    ON ict371_q9.deliveries (farmer_id, delivered_on);
ANALYZE ict371_q9.deliveries;

EXPLAIN
SELECT delivery_id, grade, weight_kg, total_value
FROM ict371_q9.deliveries
WHERE farmer_id = 1
  AND delivered_on BETWEEN DATE '2026-11-20' AND DATE '2026-11-30';

-- (g) PROCEDURE: recompute a date's total weight and total value.
CREATE OR REPLACE PROCEDURE ict371_q9.pr_refresh_purchases(p_day DATE)
LANGUAGE plpgsql
SET search_path = ict371_q9, pg_temp
AS $$
DECLARE v_weight NUMERIC(14,2); v_value NUMERIC(14,2);
BEGIN
    IF p_day IS NULL THEN RAISE EXCEPTION 'Purchase date cannot be NULL'; END IF;

    SELECT COALESCE(SUM(weight_kg), 0)::NUMERIC(14,2),
           COALESCE(SUM(total_value), 0)::NUMERIC(14,2)
      INTO v_weight, v_value
      FROM ict371_q9.deliveries
     WHERE delivered_on = p_day;

    INSERT INTO ict371_q9.daily_purchases(purchase_date, total_weight, total_value)
    VALUES (p_day, v_weight, v_value)
    ON CONFLICT (purchase_date)
    DO UPDATE SET total_weight = EXCLUDED.total_weight,
                  total_value = EXCLUDED.total_value;
END;
$$;

