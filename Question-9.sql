-- (a) DATABASE AND SEED DATA
CREATE SCHEMA IF NOT EXISTS ict371_q9;
SET search_path TO ict371_q9, public;

DROP VIEW IF EXISTS ict371_q9.v_farmer_amount_due CASCADE;
DROP TABLE IF EXISTS ict371_q9.daily_purchases CASCADE;
DROP TABLE IF EXISTS ict371_q9.deliveries CASCADE;
DROP TABLE IF EXISTS ict371_q9.farmers CASCADE;

CREATE TABLE ict371_q9.farmers (
    farmer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_number VARCHAR(20) NOT NULL UNIQUE,
    full_name VARCHAR(100) NOT NULL
);

CREATE TABLE ict371_q9.deliveries (
    delivery_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id INTEGER NOT NULL REFERENCES ict371_q9.farmers(farmer_id),
    grade CHAR(1) NOT NULL CHECK (grade IN ('A', 'B', 'C')),
    weight_kg NUMERIC(12,2) NOT NULL CHECK (weight_kg > 0),
    unit_rate NUMERIC(8,2) NOT NULL CHECK (unit_rate > 0),
    total_value NUMERIC(14,2) NOT NULL CHECK (total_value > 0),
    delivered_on DATE NOT NULL,
    is_paid BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE ict371_q9.daily_purchases (
    purchase_date DATE PRIMARY KEY,
    total_weight NUMERIC(14,2) NOT NULL CHECK (total_weight >= 0),
    total_value NUMERIC(14,2) NOT NULL CHECK (total_value >= 0)
);

